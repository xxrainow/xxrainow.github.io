import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { projects } from './projects.js';
import { escapeHTML, renderProject, renderIndex } from './project-template.js';

// GitHub Pages는 서버 라우터가 없으므로 고유 주소마다 실제 index.html을 생성합니다.
const check = process.argv.includes('--check');
const marker = '<!-- Generated by generate-project-pages.mjs; edit projects.js instead. -->';
const seen = new Set();
function documentHTML({ title, description, body, slug, prefix }) {
  const e = escapeHTML;
  return `<!doctype html>\n${marker}\n<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><meta name="theme-color" content="#0c0c0d"><title>${e(title)} — xxrainow</title><meta name="description" content="${e(description)}"><link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E%3Crect width='64' height='64' rx='16' fill='%230c0c0d'/%3E%3Ctext x='32' y='44' text-anchor='middle' fill='%23ededeb' font-size='46' font-family='Georgia'%3Ex%3C/text%3E%3C/svg%3E"><link rel="stylesheet" href="${prefix}project-detail.css"><script type="module" src="${prefix}project-detail.js"></script></head><body${slug ? ` data-project-slug="${e(slug)}"` : ''}>${body}</body></html>\n`;
}
async function save(relative, html) {
  const url = new URL(relative, import.meta.url);
  let existing = null;
  try { existing = await readFile(url, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (check) {
    if (existing !== html) throw new Error(`Page is out of date: ${relative}. Run node studio/generate-project-pages.mjs`);
    return;
  }
  if (existing && !existing.includes(marker)) throw new Error(`Refusing to overwrite a manually authored page: ${relative}`);
  await mkdir(new URL('.', url), { recursive: true });
  await writeFile(url, html);
}
for (const project of projects) {
  if (!/^[a-z0-9]+(?:[.-][a-z0-9]+)*$/.test(project.slug)) throw new Error(`Use lowercase letters/numbers separated by single dots or hyphens: ${project.slug}`);
  if (seen.has(project.slug)) throw new Error(`Duplicate project slug: ${project.slug}`);
  seen.add(project.slug);
  await save(`project/${project.slug}/index.html`, documentHTML({ title: project.title, description: project.description || project.title, body: renderProject(project, projects), slug: project.slug, prefix: '../../' }));
}
await save('project/index.html', documentHTML({title:'Projects',description:'Explore individual xxrainow projects.',body:renderIndex(projects),prefix:'../'}));
console.log(`${check ? 'Verified' : 'Generated'} ${projects.length} project pages and the project directory in ${fileURLToPath(new URL('project/', import.meta.url))}`);
